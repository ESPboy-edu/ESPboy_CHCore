#!/usr/bin/env python3
"""Reproduce the CHGame port from the pinned, unmodified BSD ATMlib sources."""
from pathlib import Path
import math
import re

ROOT = Path(__file__).resolve().parents[1]
UP = ROOT / "vendor/ATMlib"
OUT = ROOT / "src/atm"
OUT.mkdir(parents=True, exist_ok=True)
header = (UP / "ATMlib.h").read_text().split('#define ATM__PHASE(N)', 1)[0]
header = header.replace('#include <Arduino.h>', '''#include <string.h>
typedef uint8_t byte;
typedef uint16_t word;
#define PROGMEM
static inline uint8_t pgm_read_byte(const void *p) { return *(const uint8_t *)p; }
// Packed song offsets are unaligned; RISC-V cannot dereference a word here.
static inline uint16_t pgm_read_word(const void *p) {
  const uint8_t *b = (const uint8_t *)p;
  return uint16_t(b[0]) | (uint16_t(b[1]) << 8);
}
''')
header = header.replace('typedef uint16_t word;', '')
header = re.sub(r'\bword\b', 'uint16_t', header)
header += '\n#endif\n'
(OUT / "ATMlib.h").write_text('// Generated by tools/port_atmlib.py; see vendor/ATMlib/LICENSE.\n' + header)
code = (UP / "ATMlibimpl.h").read_text()
code = code.replace('ATMLIB_CONSTRUCT_ISR(OCR4A)', 'uint16_t cia = 625, cia_count = 1;\nuint8_t TIMSK4 = 0; // Logical playback flag; no AVR registers.')
# Register setup belongs to the CHGame backend; disable the unused SFX API.
code = re.sub(r'  TCCR4A = .*?\n#endif', '', code, count=1, flags=re.S)
# read_vle in upstream increments the pointer-to-pointer instead of the stream.
code = code.replace('pgm_read_byte(*pp++)', 'pgm_read_byte((*pp)++)')
# These are signed effect amounts even on targets whose plain char is unsigned.
code = code.replace('char volFreSlide;', 'int8_t volFreSlide;').replace('char transConfig;', 'int8_t transConfig;').replace('char glisConfig;', 'int8_t glisConfig;')
# Use equal-tempered A440. Upstream's AVR-specific increments detune RISC-V.
freq = [0] + [round(440 * 2 ** ((n + 35 - 69) / 12) * 65536 / 31250) for n in range(1, 64)]
a = code.index('  0,\n#if ATM_OCTAVE_2'); b = code.index('\n};', a)
code = code[:a] + '  ' + ', '.join(map(str, freq)) + code[b:]
# Clamp indexed reads after transposition/arpeggios rather than reading past flash.
code = code.replace('#define ATM__FREQ(note) pgm_read_word(&noteTable[note])', '#define ATM__FREQ(note) (((unsigned)(note) < 64u) ? pgm_read_word(&noteTable[note]) : 0)')
code = code.replace('pgm_read_word(ch->ptr++)', 'pgm_read_byte(ch->ptr++)')
code = code.replace('if (ch->note = cmd)', 'if ((ch->note = cmd))')
# Upstream's dangling elses skip volume clamping. Keep each clamp explicit.
code = code.replace('else if (ch->volFreConfig & 0x40) if (vf > 9397) vf = 9397;\n            else if (!(ch->volFreConfig & 0x40)) if (vf > 63) vf = 63;',
                    'else if (ch->volFreConfig & 0x40) { if (vf > 9397) vf = 9397; }\n          else { if (vf > 63) vf = 63; }')
code = code.replace('else if (ch->treviConfig & 0x40) if (vt > 9397) vt = 9397;\n        else if (!(ch->treviConfig & 0x40)) if (vt > 63) vt = 63;',
                    'else if (ch->treviConfig & 0x40) { if (vt > 9397) vt = 9397; }\n      else { if (vt > 63) vt = 63; }')
code = re.sub(r'\bword\b', 'uint16_t', code)
(OUT / "ATMlibimpl.h").write_text('// Generated by tools/port_atmlib.py; see vendor/ATMlib/LICENSE.\n' + code)
(OUT / "ATMcmds.h").write_text((UP / "ATMcmds.h").read_text())
print('ATMlib CHGame port regenerated')
