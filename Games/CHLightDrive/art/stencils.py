"""Hand-placed indexed pixel stencils. '.' is outside; 0 is opaque black.

These are drawings, not primitive-generated silhouettes. Body and limb
stencils share anchors so contact, passing, recoil and flight poses can be
reviewed independently in the existing pixelpatch draw/check/redraw loop.
"""
def patch(x,y,text):
    rows=text.strip('\n').splitlines();w=max(map(len,rows))
    return {'at':[x,y],'rows':[r.ljust(w,'.') for r in rows]}

