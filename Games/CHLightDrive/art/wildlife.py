def assets():
    # Compress on the contact poses; the limbs are separately articulated.
    result={}
    for name,size,body,legs in [('deer',[32,32],DEER_BODY,DEER_LEGS),('fox',[32,22],FOX_BODY,FOX_LEGS),('hare',[24,24],HARE_BODY,HARE_LEGS)]:
        frames=[]
        for n,limbs in enumerate(legs):
            pose=HARE_FLIGHT if name=='hare' and n in (2,3,4) else body
            torso={'at':[pose['at'][0],pose['at'][1]+(n in (0,5))],'rows':pose['rows']}
            frames.append(([FOX_TAILS[n]] if name=='fox' else [])+[limbs,torso])
        result[name]={'size':size,'frames':frames}
    result['owl']={'size':[40,24],'frames':[[wing,OWL_BODY] for wing in OWL_WINGS]}
    result['crow']={'size':[24,16],'frames':[[p] for p in CROW]}
    return result
