"""Native six-pose ground gaits and feathered flight silhouettes.

Separate far/near legs describe real joints; torsos compress on contact and
rise in suspension. Black bodies are opaque. Only the exterior is '.'/15.
"""
def patch(x,y,text):
    rows=text.removeprefix('\n').removesuffix('\n').splitlines();w=max(map(len,rows))
    return {'at':[x,y],'rows':[r.ljust(w,'.') for r in rows]}

