"""Nine individually drawn trees. Frame numbers select trees, never wind poses.

Unequal boughs, open forks and bark scars are placed at native resolution.
Each drawing keeps its species' original canvas and ground anchor. Wind is
applied to the crown by the renderer, leaving these trunks and roots planted.
"""

def stencil(x,y,text):
    rows=text.strip('\n').splitlines();width=max(map(len,rows))
    return {'at':[x,y],'rows':[row.ljust(width,'.') for row in rows]}

